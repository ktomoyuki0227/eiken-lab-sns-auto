function buildPromptEntries(startIdx, endIdx) {
  let content = '';
  for (let i = startIdx; i <= endIdx; i++) {
    const [para1arr, para2arr, ctaSuffix, hashtag3] = posts[i];
    const text = buildPromptText(para1arr, para2arr, ctaSuffix, hashtag3);
    content += '\nNo.' + (i+1) + '（投稿日：' + getDate(i) + '\u3000投稿時間：07:00）\n';
    content += text + '\n\n---\n';
  }
  return content;
}

